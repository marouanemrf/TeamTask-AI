import type { CareerState } from "../../hooks/useCareerSuggestions";
import LoadingState from "../ui/LoadingState";

/**
 * AI-generated career paths from the user's own profile, shown inside the CV document (not
 * printed). Clearly labelled: generated, not job openings. "Skills you have" only ever lists skills
 * from the profile (checked on the server).
 */
function CareerSuggestions({ state, onRefresh }: { state: CareerState; onRefresh: () => void }) {
  const generatedAt = state.kind === "ready" && state.result.generatedAt ? new Date(state.result.generatedAt).toLocaleString() : null;
  return (
    <section aria-labelledby="career-title" aria-busy={state.kind === "loading"}>
      <h2 id="career-title">
        Career suggestions 
      </h2>
      <p className="form-hint">
        Generated by AI from your profile (skills, job title, summary, experience, education and projects). These are general
        career directions, <strong>not job openings</strong>, and may be imperfect.
      </p>

      {state.kind === "loading" && <LoadingState className="empty-state career-loading">Generating suggestions from your profile…</LoadingState>}

      {state.kind === "unavailable" && <p className="empty-state">Career suggestions aren't available in this environment yet.</p>}

      {state.kind === "error" && (
        <div className="chat-error" role="alert">
          <span>{state.message}</span>
          <button type="button" className="button-secondary" onClick={onRefresh}>
            Try again
          </button>
        </div>
      )}

      {state.kind === "ready" && state.result.status === "INCOMPLETE" && (
        <p className="empty-state">Add skills, a job title, a summary, experience or education to your profile to get suggestions.</p>
      )}

      {state.kind === "ready" && state.result.status === "OK" && (
        <>
          <div className="suggestion-grid">
            {(state.result.suggestions ?? []).map((s) => (
              <article className="suggestion-card" key={s.title}>
                <h4>{s.title}</h4>
                <dl className="suggestion-card__facts">
                  {s.why.length > 0 && (
                    <>
                      <dt>Why</dt>
                      <dd>{s.why.join(" ")}</dd>
                    </>
                  )}
                  <dt>Skills you have</dt>
                  <dd>{s.skillsYouHave.join(", ") || "None listed in your profile yet"}</dd>
                  <dt>Skills to develop</dt>
                  <dd>{s.skillsToDevelop.join(", ") || "—"}</dd>
                  {s.nextSteps.length > 0 && (
                    <>
                      <dt>Next steps</dt>
                      <dd>{s.nextSteps.join(" ")}</dd>
                    </>
                  )}
                </dl>
              </article>
            ))}
          </div>
          <p className="form-hint career-suggestions__meta">
            {generatedAt && <>Generated {generatedAt}. </>}Updated when you save your profile.{" "}
            <button type="button" className="text-button" onClick={onRefresh}>
              Generate again
            </button>
          </p>
        </>
      )}
    </section>
  );
}

export default CareerSuggestions;
